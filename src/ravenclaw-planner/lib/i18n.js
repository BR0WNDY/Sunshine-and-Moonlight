export const MESSAGES = { th: TH, en: EN };

export const normalizeLang = (v) => (LANGS.includes(v) ? v : DEFAULT_LANG);

/**
 * Builds the lookup every view uses: `t('addGoal')`, `t('streak', 5)`.
 * A missing key falls back to Thai, then to the key itself — a typo shows up
 * on screen as the key rather than as `undefined`.
 */
export function translator(lang) {
  const dict = MESSAGES[normalizeLang(lang)];
  return function t(key, ...args) {
    const v = key in dict ? dict[key] : TH[key];
    if (v == null) return key;
    return typeof v === 'function' ? v(...args) : v;
  };
}
